#!/usr/bin/env python3
"""Render the HP industry selector from the shared industry catalog."""
import argparse
import html
import json
from hp_management_industries import SITE, HUB_URL, HUB_SOURCE, published_industries
from site_header import apply

OUTPUT = SITE / HUB_SOURCE
BASE = 'https://simy.one'
TITLE = '業種から選ぶホームページ管理・無料診断｜SIMY'
DESCRIPTION = '業種に合ったホームページ管理のサービス内容と料金を確認できます。今お使いのホームページのURLから、業種別の無料診断を始められます。'


def minimum_price(industry):
    config = json.loads((SITE / industry['checkout_config']).read_text())
    plans = config.get('plans', {})
    if not config.get('enabled') or not plans:
        raise ValueError(f"Published industry needs enabled checkout plans: {industry['id']}")
    values = list(plans.values())
    if any(type(p.get('monthlyYen')) is not int or p['monthlyYen'] <= 0 or
           type(p.get('taxInclusiveYen')) is not int or p['taxInclusiveYen'] < p['monthlyYen'] for p in values):
        raise ValueError(f"Invalid checkout price: {industry['id']}")
    return min(values, key=lambda p: p['monthlyYen'])


def render(industries=None):
    industries = published_industries() if industries is None else industries
    esc = lambda value: html.escape(str(value), quote=True)
    cards, prices = [], []
    for item in industries:
        url, label = esc(item['url']), esc(item['label'])
        price = minimum_price(item)
        cards.append(f'''<article class="industry-card" data-industry="{esc(item['id'])}">
<h3>{label}</h3><p>{esc(item['description'])}</p>
<div class="industry-actions"><a class="hub-button" href="{url}#diagnosis">無料診断を始める<span class="sr-only">（{label}）</span></a>
<a href="{url}">サービス詳細</a><a href="{url}#pricing">料金を見る</a></div></article>''')
        prices.append(f'''<article class="industry-price"><h3>{label}</h3>
<p class="price-number">月額 <strong>{price['monthlyYen']:,}</strong>円〜（税別）<span>税込 {price['taxInclusiveYen']:,}円〜／月</span></p>
<a href="{url}#pricing">プラン・料金の詳細を見る<span class="sr-only">（{label}）</span></a></article>''')
    schema = {'@context': 'https://schema.org', '@type': 'CollectionPage', 'name': TITLE,
              'description': DESCRIPTION, 'url': BASE + HUB_URL, 'inLanguage': 'ja',
              'mainEntity': {'@type': 'ItemList', 'numberOfItems': len(industries), 'itemListElement': [
                  {'@type': 'ListItem', 'position': n, 'name': item['label'], 'url': BASE + item['url']}
                  for n, item in enumerate(industries, 1)]}}
    source = f'''<!doctype html>
<!-- Generated by scripts/build-hp-management-industries.py -->
<html lang="ja"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{TITLE}</title><meta name="description" content="{DESCRIPTION}">
<meta name="robots" content="index,follow"><link rel="canonical" href="{BASE}{HUB_URL}">
<meta property="og:type" content="website"><meta property="og:locale" content="ja_JP"><meta property="og:site_name" content="SIMY">
<meta property="og:url" content="{BASE}{HUB_URL}"><meta property="og:title" content="{TITLE}">
<meta property="og:description" content="{DESCRIPTION}"><meta name="twitter:title" content="{TITLE}"><meta name="twitter:description" content="{DESCRIPTION}">
<link rel="icon" href="/simy-icon-56.png"><link rel="stylesheet" href="/site-theme.css"><link rel="stylesheet" href="/hp-management-industries.css">
<script type="application/ld+json">{json.dumps(schema, ensure_ascii=False).replace('<', '&lt;')}</script>
</head><body class="hp-industries-page"><a class="hub-skip" href="#main">本文へ移動</a>
<main id="main" class="industry-hub"><section class="hub-intro" aria-labelledby="hub-title">
<p class="hub-eyebrow">SIMY ホームページ管理</p><h1 id="hub-title">業種に合ったホームページ管理を。</h1>
<p>今あるホームページを、安心して更新し続けるために。<br>業種に合ったサービスを選び、URLから無料診断を始められます。</p>
<a class="hub-button" href="#industries">業種を選んで無料診断へ</a></section>
<section id="industries" aria-labelledby="industries-title"><h2 id="industries-title">業種からサービスを選ぶ</h2>
<p class="section-lead">サービス内容・料金・無料診断は、それぞれの業種のページでご案内します。</p>
<div class="industry-grid">{''.join(cards)}</div></section>
<section id="pricing" aria-labelledby="pricing-title"><h2 id="pricing-title">業種別の料金</h2>
<p class="section-lead">現在ご案内している各業種の最小月額です。プランの範囲や追加オプションは、各サービスの料金をご確認ください。</p>
<div class="industry-grid">{''.join(prices)}</div></section>
</main><footer class="hub-footer"><a href="/ja.html">SIMY</a><a href="/contact.html?lang=ja">お問い合わせ</a><a href="/seller-info.html">特定商取引法に基づく表記</a></footer></body></html>
'''
    return apply(source, OUTPUT)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            raise SystemExit('HP industry hub differs; run python3 scripts/build-hp-management-industries.py')
        print('Checked HP industry hub')
    else:
        OUTPUT.write_text(output)
        print('Built HP industry hub')

if __name__ == '__main__':
    main()
