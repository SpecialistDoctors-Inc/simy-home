#!/usr/bin/env python3
"""Generate six pharma pages from the Japanese template and reviewed locale copy."""
import argparse
import html
import json
import re
from pathlib import Path
from site_header import apply as apply_header
from pharmaceutical_manga_art import render_artwork

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'site'
LOCALES = ('ja', 'en', 'es', 'fr', 'hi', 'zh-Hans')
COPY = json.loads((ROOT / 'scripts/pharmaceutical-locales.json').read_text())
TEMPLATE = (ROOT / 'scripts/pharmaceutical-ja.html').read_text()

def route(locale):
    return '/for/' + ('' if locale == 'ja' else locale.lower() + '/') + 'pharmaceutical-companies/'

def render(locale, require_manga_art=False):
    source = TEMPLATE
    if locale != 'ja':
        dictionary = COPY[locale]
        def text_node(match):
            value = html.unescape(match[0])
            key = value.strip()
            if not key or not re.search(r'[\u3000-\u9fff]', key):
                return match[0]
            if key not in dictionary:
                raise ValueError(f'{locale}: Missing translation: {key}')
            return html.escape(value[:len(value)-len(value.lstrip())] + dictionary[key] + value[len(value.rstrip()):], quote=False)
        source = re.sub(r'(?<=>)[^<>]+(?=<)', text_node, source)
        def attribute(match):
            value = html.unescape(match[2])
            if not re.search(r'[\u3000-\u9fff]', value):
                return match[0]
            if value not in dictionary:
                raise ValueError(f'{locale}: Missing attribute translation: {value}')
            return match[1] + html.escape(dictionary[value], quote=True) + '"'
        source = re.sub(r'((?:alt|content)=")([^"]*)"', attribute, source)
    if locale == 'ja':
        # Keep the two short phrases intact on narrow screens.
        source = source.replace(
            '<em>練習を、次の面談に活かす。</em>',
            '<em><span class="headline-part">練習を、</span><wbr>'
            '<span class="headline-part">次の面談に活かす。</span></em>')
    if locale not in ('ja', 'zh-Hans'):
        source = source.replace('</span><wbr>', '</span> <wbr>')
    source = source.replace('<html lang="ja"', f'<html lang="{locale}"')
    source = re.sub(r'<link rel="(?:canonical|alternate)"[^>]*>\n?', '', source)
    links = f'<link rel="canonical" href="https://simy.one{route(locale)}">\n'
    links += ''.join(f'<link rel="alternate" hreflang="{code}" href="https://simy.one{route(code)}">\n' for code in LOCALES)
    links += f'<link rel="alternate" hreflang="x-default" href="https://simy.one{route("en")}">\n'
    source = source.replace('</head>', links + '</head>')
    source = re.sub(r'(<meta property="og:url" content=")[^"]*', lambda m: m[1] + 'https://simy.one' + route(locale), source)
    if locale != 'ja':
        source = source.replace('href="/for/"', 'href="/for/en/"')
        source = source.replace('href="/for/engineers/"', f'href="/for/{locale.lower()}/engineers/"')
        source = source.replace('/contact.html?lang=ja', f'/contact.html?lang={locale}')
    source = render_artwork(source, required=require_manga_art)
    title = html.unescape(re.search(r'<title>(.*?)</title>', source)[1])
    schema = {'@context': 'https://schema.org', '@type': 'WebPage', 'name': title,
              'url': 'https://simy.one' + route(locale), 'inLanguage': locale,
              'isPartOf': {'@type': 'WebSite', 'name': 'SIMY', 'url': 'https://simy.one/'}}
    source = source.replace('</head>', '<script type="application/ld+json">' + json.dumps(schema, ensure_ascii=False) + '</script>\n</head>')
    source = source.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-pharmaceutical-pages.py; edit scripts/pharmaceutical-ja.html and scripts/pharmaceutical-locales.json. -->')
    return apply_header(source, SITE / (route(locale).lstrip('/') + 'index.html'))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--require-manga-art', action='store_true',
                        help='Require and validate all eight distinct full-scene illustrations')
    args = parser.parse_args()
    for locale in LOCALES:
        path = SITE / (route(locale).lstrip('/') + 'index.html')
        output = render(locale, require_manga_art=args.require_manga_art)
        if args.check:
            if not path.exists() or path.read_text() != output:
                raise SystemExit(f'Stale pharmaceutical page: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output)
    print('6 pharmaceutical pages ' + ('verified.' if args.check else 'generated.'))

if __name__ == '__main__':
    main()
